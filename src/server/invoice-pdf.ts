import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import QRCode from "qrcode";
import { getInvoice, type Invoice } from "@/server/payments";
import { createUpiRequest } from "@/server/upi";

const merchantName = process.env.UPI_MERCHANT_NAME || "LoopLedger Technologies Pvt Ltd";
const merchantVpa = process.env.UPI_MERCHANT_VPA || process.env.UPI_VPA || "loopledger@icici";

function money(paise: number): string {
  return `INR ${(paise / 100).toLocaleString("en-IN", { minimumFractionDigits: 2 })}`;
}

function drawText(page: ReturnType<PDFDocument["addPage"]>, text: string, x: number, y: number, size: number, font: Awaited<ReturnType<PDFDocument["embedFont"]>>, color = rgb(0.09, 0.13, 0.2)) {
  page.drawText(text, { x, y, size, font, color });
}

export async function createInvoicePdf(invoice: Invoice): Promise<Uint8Array> {
  const document = await PDFDocument.create();
  const page = document.addPage([595, 842]);
  const regular = await document.embedFont(StandardFonts.Helvetica);
  const bold = await document.embedFont(StandardFonts.HelveticaBold);
  const purple = rgb(0.23, 0.19, 0.85);
  const muted = rgb(0.4, 0.43, 0.5);
  const balance = invoice.total - invoice.paidTotal;

  page.drawRectangle({ x: 0, y: 792, width: 595, height: 50, color: purple });
  drawText(page, merchantName, 40, 812, 18, bold, rgb(1, 1, 1));
  drawText(page, "TAX INVOICE / PAYMENT RECEIPT", 365, 815, 9, regular, rgb(1, 1, 1));
  drawText(page, `Invoice ${invoice.number}`, 40, 755, 16, bold);
  drawText(page, `Status: ${invoice.status}`, 40, 733, 10, regular, muted);
  drawText(page, `Due date: ${invoice.dueDate}`, 40, 716, 10, regular, muted);
  drawText(page, "BILL TO", 350, 755, 9, bold, purple);
  drawText(page, invoice.customer, 350, 735, 11, bold);
  drawText(page, "GSTIN: 27AAAC1234F1ZQ", 350, 717, 9, regular, muted);

  page.drawRectangle({ x: 40, y: 650, width: 515, height: 30, color: rgb(0.94, 0.94, 1) });
  drawText(page, "DESCRIPTION", 52, 661, 9, bold, muted);
  drawText(page, "AMOUNT", 450, 661, 9, bold, muted);
  drawText(page, "Subscription services", 52, 625, 11, regular);
  drawText(page, money(invoice.total), 450, 625, 11, regular);
  page.drawLine({ start: { x: 40, y: 605 }, end: { x: 555, y: 605 }, thickness: 1, color: rgb(0.88, 0.89, 0.94) });
  drawText(page, "Total invoiced", 350, 580, 10, regular, muted);
  drawText(page, money(invoice.total), 450, 580, 10, bold);
  drawText(page, "Total paid", 350, 558, 10, regular, muted);
  drawText(page, money(invoice.paidTotal), 450, 558, 10, regular);
  drawText(page, "Balance due", 350, 530, 11, bold, purple);
  drawText(page, money(balance), 450, 530, 11, bold, purple);

  let y = 475;
  drawText(page, "PAYMENT HISTORY", 40, y, 10, bold, purple);
  y -= 24;
  if (invoice.payments.length === 0) {
    drawText(page, "No payments recorded.", 40, y, 10, regular, muted);
  } else {
    for (const payment of invoice.payments) {
      drawText(page, `${payment.paidOn} - ${payment.method}`, 40, y, 10, regular);
      drawText(page, money(payment.amount), 450, y, 10, regular);
      y -= 20;
    }
  }

  if (balance > 0) {
    const upi = createUpiRequest(invoice);
    const qrData = await QRCode.toDataURL(upi.uri, { width: 160, margin: 1 });
    const qrImage = await document.embedPng(Buffer.from(qrData.split(",")[1], "base64"));
    page.drawImage(qrImage, { x: 385, y: 285, width: 130, height: 130 });
    drawText(page, "Scan to pay by UPI", 402, 270, 9, bold, purple);
    drawText(page, merchantVpa, 402, 254, 8, regular, muted);
  } else {
    drawText(page, "PAID IN FULL", 385, 330, 16, bold, rgb(0, 0.55, 0.4));
  }

  page.drawLine({ start: { x: 40, y: 100 }, end: { x: 555, y: 100 }, thickness: 1, color: rgb(0.88, 0.89, 0.94) });
  drawText(page, "Thank you for your business.", 40, 78, 9, regular, muted);
  drawText(page, "Generated by LoopLedger Billing Cloud", 365, 78, 8, regular, muted);
  return document.save();
}

export async function getInvoicePdf(invoiceId: string, customerId?: string | null): Promise<{ invoice: Invoice; bytes: Uint8Array }> {
  const invoice = await getInvoice(invoiceId, customerId);
  return { invoice, bytes: await createInvoicePdf(invoice) };
}
